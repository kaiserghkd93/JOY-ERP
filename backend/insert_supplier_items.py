def parse_price(v):
    if not v:
        return 0.0
    s = str(v).replace(',', '').replace(' ', '').strip()
    try:
        return float(s)
    except Exception:
        return 0.0


def normalize_code(c):
    # 공백 제거 후 앞뒤 트림
    return c.replace(' ', '').strip()


SKIP_NAMES = {'소계', '전동치솔', 'ATC BOX70MM', 'bracket 70mm', 'ATC BOX 70MM',
              '70mm  bracket', '대양각인코어', 'TAPU COVER', 'TAPU BASE', 'WASHER',
              'BODY', 'CUP HOLDER', 'CAP', 'TRAY', 'JACK FRAME',
              'FOLDER / BASE PLATE', 'FOLDER / TRAY', 'FOLDER / TRAY BAND',
              'LOWER CASE', 'upper bracket - l', 'UPPERBRACKET - R', 'TOP COVER', 'SIDE PLATE',
              'X-FLOAT 720MM', 'X-FLOAT 500MM', 'BRACKET 75mm', 'BRACKET 105mm', 'BRACKET 135mm',
              'DC COIL FRAME', 'jh4 cartrdidge', 'jh4 cartrdidge-1X (반제품)',
              'JF2 BUSBAR LD #3', 'JF2 BUSBAR LD #4', 'JF2 BUSBAR RD #3', 'JF2 BUSBAR RD #4',
              'JF2 SUPPORT BRACKET ', 'JH4 END COVER',
              '주사기 손잡이(소)', '주사기 손잡이(대)'}

rows = []
seen = {}  # part_no → index in rows (for dedup: keep latest price)

for line in RAW.strip().splitlines():
    cols = line.split('\t')
    # pad to 8 cols
    while len(cols) < 8:
        cols.append('')

    customer_raw = cols[0].strip()
    part_no_raw  = cols[2].strip()
    name_raw     = cols[3].strip()
    unit_raw     = cols[5].strip().upper() or 'EA'
    price_raw    = cols[6]
    buy_raw      = cols[7]

    # skip empty part_no or skip-list names
    if not part_no_raw:
        continue
    if name_raw in SKIP_NAMES or name_raw == '':
        continue

    # normalize: remove internal spaces from code
    part_no = normalize_code(part_no_raw)
    if not part_no:
        continue

    sell_price = parse_price(price_raw)
    buy_price  = parse_price(buy_raw)

    if part_no in seen:
        # update existing: merge prices (keep nonzero), accumulate customers
        r = rows[seen[part_no]]
        if sell_price > 0:
            r['sell'] = sell_price
        if buy_price > 0:
            r['buy'] = buy_price
        if customer_raw and customer_raw not in r['customers']:
            r['customers'].append(customer_raw)
    else:
        seen[part_no] = len(rows)
        rows.append({
            'part_no': part_no,
            'name': name_raw,
            'unit': unit_raw if unit_raw in ('EA','KG','M','SET','L') else 'EA',
            'sell': sell_price,
            'buy': buy_price,
            'customers': [customer_raw] if customer_raw else [],
        })

print(f"파싱된 품목 수: {len(rows)}")

conn = sqlite3.connect(DB)
cur = conn.cursor()

created = updated = skipped = 0

for r in rows:
    cur.execute("SELECT part_no FROM item WHERE part_no=?", (r['part_no'],))
    existing = cur.fetchone()
    spec = ', '.join(r['customers']) if len(r['customers']) > 1 else (r['customers'][0] if r['customers'] else None)

    if existing:
        cur.execute("""
            UPDATE item SET name=?, unit=?, spec=?,
              std_sell_price=CASE WHEN ?>0 THEN ? ELSE std_sell_price END,
              std_buy_price =CASE WHEN ?>0 THEN ? ELSE std_buy_price  END
            WHERE part_no=?
        """, (r['name'], r['unit'], spec,
              r['sell'], r['sell'],
              r['buy'],  r['buy'],
              r['part_no']))
        updated += 1
    else:
        try:
            cur.execute("""
                INSERT INTO item (part_no, name, spec, unit, item_type,
                  std_buy_price, std_sell_price, safety_stock, moq, active, created_at)
                VALUES (?,?,?,?,'외주품',?,?,0,1,1,datetime('now'))
            """, (r['part_no'], r['name'], spec, r['unit'], r['buy'], r['sell']))
            created += 1
        except Exception as e:
            print(f"  오류: {r['part_no']} - {e}")
            skipped += 1

conn.commit()
conn.close()
print(f"완료 → 신규: {created}건 / 수정: {updated}건 / 오류: {skipped}건")
